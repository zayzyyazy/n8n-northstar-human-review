import assert from 'node:assert/strict';
import {load, readExample, verifyExample} from './harness.mjs';
const run=load('northstar');
const input=readExample('input');
const hard=(await run('Evaluate Hard Rules',input))[0].json;
const guarded=(await run('Apply Final Decision Guardrails',hard))[0].json;
assert.equal(guarded.final_decision.action,'MANUAL_REVIEW');
assert.equal(guarded.final_decision.source,'HARD_RULE');
assert.equal(guarded.final_decision.confidence,null);
verifyExample('output',guarded.final_decision);
const invalid=(await run('Parse AI Decision',{message:{content:'not json'}},{'Prepare Decision Context':input}))[0].json;
assert.equal(invalid.ai_result.parse_success,false);
assert.equal((await run('Apply Final Decision Guardrails',invalid))[0].json.final_decision.action,'MANUAL_REVIEW');
const forbidden=(await run('Apply Final Decision Guardrails',{...input,ai_result:{parse_success:true,decision:'REFUND'}}))[0].json;
assert.equal(forbidden.final_decision.source,'VALIDATION_FALLBACK');
await assert.rejects(run('Parse AI Decision',{}, {'Prepare Decision Context':input}), /no message content/);
const learned={...input,policy_match_result:{matched_policies:[{id:'EXAMPLE_POLICY',name:'Synthetic approved guidance',group:'LEARNED',preferred_action:'REFURBISH'}]}};
assert.equal((await run('Apply Final Decision Guardrails',learned))[0].json.final_decision.action,'REFURBISH');
assert.equal((await run('Apply Final Decision Guardrails',{...learned,hard_rule_result:{forced_action:'SCRAP'}}))[0].json.final_decision.action,'SCRAP');
const row={category:'outerwear',condition:'major damage',system_decision:'SCRAP',human_decision:'MANUAL_REVIEW',sku:'EXAMPLE_SKU',condition_note:'Synthetic inspection',override_reason:'Synthetic review'};
const duplicate=[{...row,return_id:'EXAMPLE_RETURN_1'},{...row,return_id:'EXAMPLE_RETURN_1'},{...row,return_id:'EXAMPLE_RETURN_2'}];
assert.equal((await run('Detect Correction Patterns',duplicate))[0].json.candidate_rule_ready,false);
const pattern=(await run('Detect Correction Patterns',[...duplicate,{...row,return_id:'EXAMPLE_RETURN_3'}]))[0].json;
assert.equal(pattern.occurrence_count,3);
assert.equal(pattern.candidate_rule_ready,true);
const candidate=(await run('Generate Candidate Rule',pattern))[0].json;
assert.equal(candidate.approval_status,'PENDING');
verifyExample('candidate-output',candidate);
const unknown=(await run('Lookup Northstar Product',{sku:'EXAMPLE_UNKNOWN_SKU'}))[0].json;
assert.equal(unknown.product_found,false);
console.log('PASS: NORTHSTAR action validation, AI parsing, hard-rule precedence, candidate threshold, and unknown-SKU checks; fixtures match.');
